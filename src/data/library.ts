export function getPassageById(id: string): Passage | undefined {
	return PASSAGES.find((p) => p.id === id);
}

export function getPassagesByCategory(category: Category): Passage[] {
	return PASSAGES.filter((p) => p.category === category);
}

export function getCategoryMeta(category: Category): CategoryMeta {
	return CATEGORIES.find((c) => c.id === category) as CategoryMeta;
}
